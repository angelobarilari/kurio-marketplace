export const createNfts = (): Nft[] =>
  catalogFixtures.map(({ imageKey, featured = false, rare = false, ...fixture }, index) => ({
    ...fixture,
    image: nftImages[imageKey],
    featured,
    rare,
    available: true,
    createdAt: new Date(Date.UTC(2026, 10, 12 - index)).toISOString(),
    version: 1,
  }))

const createEditions = (nft: Nft): NftEdition[] => {
  const candidates: NftEdition[] = [
    {
      id: 'default',
      label: nft.edition,
      priceEth: nft.priceEth,
      availableQuantity: nft.available ? 8 : 0,
      maxPerOrder: 5,
    },
    { id: 'one-of-one', label: '1/1', priceEth: '4.90', availableQuantity: 0, maxPerOrder: 1 },
    { id: 'one-of-ten', label: '1/10', priceEth: '2.40', availableQuantity: 3, maxPerOrder: 2 },
    { id: 'open', label: 'ABERTA', priceEth: '0.69', availableQuantity: 50, maxPerOrder: 10 },
  ]
  return candidates.filter(
    (edition, index) => candidates.findIndex((candidate) => candidate.label === edition.label) === index,
  )
}

export const createNftDetail = (nft: Nft, allNfts: readonly Nft[]): NftDetail => {
  const isEmeraldApe = nft.id === 'emerald-ape-042'
  const collectionDescription = `Um colecionável digital ${nft.edition} finalizado à mão da coleção ${nft.collection}, verificado na ${nft.network}.`

  return {
    ...nft,
    gallery: Array.from({ length: 4 }, (_, index) => ({
      id: `${nft.id}-media-${index + 1}`,
      src: nft.image,
      alt: `${nft.name} ${nft.tokenId}${index === 0 ? '' : ` — vista ${index + 1}`}`,
    })),
    shortDescription: isEmeraldApe
      ? 'Um colecionável digital 1/50 finalizado à mão da coleção Kurio Editions, verificado na Ethereum.'
      : collectionDescription,
    description: [
      `${nft.name} ${nft.tokenId} é uma obra digital ${nft.edition} da coleção ${nft.collection}. Cada atributo fica armazenado nos metadados do token e verificado na ${nft.network}.`,
      'A propriedade inclui a arte em alta resolução, lançamentos exclusivos para colecionadores e um registro permanente de procedência na rede.',
    ],
    creator: { id: 'nova-sato', name: 'Nova Sato' },
    attributes: [
      { trait: 'Estilo', value: isEmeraldApe ? 'Óculos' : 'Digital' },
      { trait: 'Cor', value: isEmeraldApe ? 'Esmeralda' : 'Kurio' },
      { trait: 'Raridade', value: nft.rare || isEmeraldApe ? 'Raro' : 'Selecionado' },
    ],
    editions: createEditions(nft),
    rating: { average: isEmeraldApe ? 4.8 : 4.6, count: isEmeraldApe ? 19 : 12 },
    provenance: {
      tokenStandard: 'ERC-721',
      contractAddress: '0x7A42...19E8',
      storage: 'IPFS',
      royaltyPercent: '5',
    },
    relatedNfts: allNfts
      .filter((candidate) => candidate.id !== nft.id && candidate.collection === nft.collection)
      .slice(0, 5),
  }
}

